#pragma once

#include <vector>
#include <string>

namespace fg
{

    //------------------------------------------------------------
    // اندازه تصویر
    //------------------------------------------------------------

    struct Size
    {
        int width = 0;
        int height = 0;
    };

    //------------------------------------------------------------
    // نقطه
    //------------------------------------------------------------

    struct Point
    {
        float x = 0;
        float y = 0;
    };

    //------------------------------------------------------------
    // مستطیل
    //------------------------------------------------------------

    struct Rect
    {
        float left = 0;
        float top = 0;
        float width = 0;
        float height = 0;
    };

    //------------------------------------------------------------
    // نتیجه تشخیص یک چهره
    //------------------------------------------------------------

    struct Face
    {
        Rect rect;

        float score = 0.0f;

        std::vector<Point> landmarks;

        std::vector<float> embedding;
    };

    //------------------------------------------------------------
    // یک تصویر
    //------------------------------------------------------------

    struct ImageInfo
    {
        std::string fileName;

        Size size;

        std::vector<Face> faces;
    };

    //------------------------------------------------------------
    // گروه افراد مشابه
    //------------------------------------------------------------

    struct PersonGroup
    {
        int id = 0;

        std::vector<int> imageIndexes;
    };

    //------------------------------------------------------------
    // تنظیمات تشخیص چهره
    //------------------------------------------------------------

    struct FaceDetectorOptions
    {
        float scoreThreshold = 0.9f;

        float nmsThreshold = 0.3f;

        int topK = 5000;

        int inputWidth = 320;

        int inputHeight = 320;
    };

    //------------------------------------------------------------
    // تنظیمات استخراج ویژگی
    //------------------------------------------------------------

    struct RecognizerOptions
    {
        bool normalizeEmbedding = true;
    };

    //------------------------------------------------------------
    // تنظیمات خوشه‌بندی
    //------------------------------------------------------------

    struct ClusterOptions
    {
        float eps = 0.55f;

        int minSamples = 2;
    };

}